func describeBoleto(b *boleto.Boleto) string {
	parts := []string{"ok", b.Type.String(), b.Barcode, b.DigitableLine, b.Formatted(), strconv.FormatInt(b.AmountCents, 10)}
	if bk := b.Bancario; bk != nil {
		parts = append(parts, bk.BankCode, bk.BankName, strconv.Itoa(bk.Currency), strconv.Itoa(bk.Factor), bk.FreeField)
	}
	if a := b.Arrecadacao; a != nil {
		parts = append(parts, strconv.Itoa(int(a.Segment)), a.Segment.String(), strconv.Itoa(a.ValueType), strconv.FormatBool(a.ValueIsReference),
			strconv.Itoa(a.Modulus), a.CompanyID, a.CNPJBase, a.FreeField)
	}
	return strings.Join(parts, "|")
}

