func lintLines(s string) string {
	var lines []string
	for _, i := range pix.Lint(s) {
		lines = append(lines, i.String())
	}
	return strings.Join(lines, "\n")
}

func tlv(id, v string) string { return fmt.Sprintf("%s%02d%s", id, len(v), v) }

