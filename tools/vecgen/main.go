var rng = rand.New(rand.NewSource(20260221))

// mutationRunes are inserted or substituted into valid inputs. They include
// multi-byte characters so that byte-versus-character semantics are covered.
var mutationRunes = []rune("0123456789ABCDEFXYZabcdefxyz.-/ *@+:,\tãóé€🙂")

func randRune() rune { return mutationRunes[rng.Intn(len(mutationRunes))] }

// mutate applies one random edit: replace, insert or delete a character.
func mutate(s string) string {
	r := []rune(s)
	if len(r) == 0 {
		return string(randRune())
	}
	i := rng.Intn(len(r))
	switch rng.Intn(3) {
	case 0:
		r[i] = randRune()
	case 1:
		r = append(r[:i], append([]rune{randRune()}, r[i:]...)...)
	default:
		r = append(r[:i], r[i+1:]...)
	}
	return string(r)
}

func digits(n int) string {
	var b strings.Builder
	for i := 0; i < n; i++ {
		b.WriteByte(byte('0' + rng.Intn(10)))
	}
	return b.String()
}

func alnumUpper(n int) string {
	const a = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
	var b strings.Builder
	for i := 0; i < n; i++ {
		b.WriteByte(a[rng.Intn(len(a))])
	}
	return b.String()
}

// lit renders s as a C# string literal. Non-ASCII and control characters
// are written as \u escapes so the generated file is pure ASCII.
func lit(s string) string {
	if !utf8.ValidString(s) {
		panic(fmt.Sprintf("invalid UTF-8 in vector: %q", s))
	}
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r >= 0x20 && r < 0x7F:
			b.WriteRune(r)
		default:
			for _, u := range utf16.Encode([]rune{r}) {
				fmt.Fprintf(&b, `\u%04X`, u)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

// splitsUTF8 reports whether parsing s yields a value that is not valid
// UTF-8, i.e. a declared length that cuts a multi-byte character in half.
// Go keeps the raw bytes while .NET strings hold U+FFFD, so such inputs are
// a documented representational difference and are left out of the vectors.
func splitsUTF8(s string) bool {
	var bad func([]emv.Field) bool
	bad = func(fs []emv.Field) bool {
		for _, f := range fs {
			if !utf8.ValidString(f.Value) || bad(f.Children) {
				return true
			}
		}
		return false
	}
	for _, in := range []string{s, strings.TrimSpace(s)} {
		if fields, err := emv.Parse(in); err == nil && bad(fields) {
			return true
		}
	}
	return false
}

func errStr(err error) string {
	if err == nil {
		return ""
	}
	return err.Error()
}

type writer struct{ b bytes.Buffer }

func (w *writer) f(format string, args ...any) { fmt.Fprintf(&w.b, format, args...) }

func (w *writer) table(name, tupleType string, rows [][]string) {
	w.f("\n    public static readonly %s[] %s =\n    {\n", tupleType, name)
	for _, r := range rows {
		w.f("        (%s),\n", strings.Join(r, ", "))
	}
	w.f("    };\n")
}

func uniq(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range in {
		if !seen[s] && utf8.ValidString(s) {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

