func genCRC(w *writer) {
	inputs := []string{"123456789", "", "A", "hello world", bcbExample[:len(bcbExample)-4], "São Paulo", "Niterói 2026", "🙂 pix"}
	for i := 0; i < 24; i++ {
		inputs = append(inputs, mutate(mutate(bcbExample)))
	}
	var rows [][]string
	for _, s := range uniq(inputs) {
		rows = append(rows, []string{lit(s), lit(emv.CRC16(s))})
	}
	w.table("Crc", "(string Input, string Hex)", rows)
}

func formatCPF(c string) string { return c[:3] + "." + c[3:6] + "." + c[6:9] + "-" + c[9:] }

func validCPF() string {
	for {
		base := digits(9)
		for s := 0; s < 100; s++ {
			c := base + fmt.Sprintf("%02d", s)
			if document.ValidateCPF(c) == nil {
				return c
			}
		}
	}
}

func validCNPJ(alnum bool) string {
	base := digits(12)
	if alnum {
		base = alnumUpper(12)
	}
	d1, d2 := document.CNPJCheckDigits(base)
	return base + strconv.Itoa(d1) + strconv.Itoa(d2)
}

func genDocuments(w *writer) {
	var bases [][]string
	for i := 0; i < 40; i++ {
		base := alnumUpper(12)
		if i%3 == 0 {
			base = digits(12)
		}
		d1, d2 := document.CNPJCheckDigits(base)
		bases = append(bases, []string{lit(base), strconv.Itoa(d1), strconv.Itoa(d2)})
	}
	w.table("CnpjCheckDigits", "(string Base, int First, int Second)", bases)

	inputs := []string{"529.982.247-25", "52998224725", "111.444.777-35", "111.111.111-11", "00000000000",
		"12.ABC.345/01DE-35", "12abc34501de35", "12ABC34501DE3A", "11.222.333/0001-81", "11.222.333/0001-80",
		"5299822472é", "52998224725é", "", "123", "AAAAAAAAAAAA00", "  529 982 247 25  ", "529_982_247_25"}
	for i := 0; i < 30; i++ {
		c := validCPF()
		if i%2 == 0 {
			c = formatCPF(c)
		}
		inputs = append(inputs, c, mutate(c))
	}
	for i := 0; i < 40; i++ {
		c := validCNPJ(i%2 == 0)
		if i%3 == 0 {
			c = strings.ToLower(c)
		}
		if i%4 == 0 {
			c = c[:2] + "." + c[2:5] + "." + c[5:8] + "/" + c[8:12] + "-" + c[12:]
		}
		inputs = append(inputs, c, mutate(c))
	}
	var rows [][]string
	for _, s := range uniq(inputs) {
		rows = append(rows, []string{lit(s), lit(document.Detect(s).String()), lit(document.Format(s)), lit(document.Mask(s)),
			lit(errStr(document.ValidateCPF(s))), lit(errStr(document.ValidateCNPJ(s))), strconv.FormatBool(document.IsAlphanumericCNPJ(s))})
	}
	w.table("Documents", "(string Input, string Kind, string Formatted, string Masked, string CpfError, string CnpjError, bool Alphanumeric)", rows)
}

func describeFields(fs []emv.Field) string {
	var parts []string
	for _, f := range fs {
		if len(f.Children) > 0 {
			parts = append(parts, f.ID+"["+describeFields(f.Children)+"]")
		} else {
			parts = append(parts, f.ID+"="+strconv.Quote(f.Value))
		}
	}
	return strings.Join(parts, " ")
}

func genTLV(w *writer) {
	inputs := []string{bcbExample, "", "0000", "000201", "000201620505031", "00020162020X", "000201AB01x", "0002010",
		"00020159XX", "00020159300123456789AB", "000201593001234567", "0002015907Niterói", "0002015906Niteró63041234",
		"00020126180014br.gov.bcb.pix5802BR63041234"}
	for i := 0; i < 120; i++ {
		s := bcbExample
		for n := rng.Intn(3) + 1; n > 0; n-- {
			s = mutate(s)
		}
		inputs = append(inputs, s)
	}
	for i := 0; i < 20; i++ {
		inputs = append(inputs, bcbExample[:rng.Intn(len(bcbExample))])
	}
	var rows [][]string
	for _, s := range uniq(inputs) {
		if splitsUTF8(s) {
			continue
		}
		parse, validate := "", ""
		fields, err := emv.Parse(s)
		if err != nil {
			parse = "err|" + err.Error()
		} else {
			parse = "ok|" + describeFields(fields)
			validate = errStr(emv.Validate(fields))
		}
		rows = append(rows, []string{lit(s), lit(parse), lit(validate), lit(errStr(emv.VerifyCRC(s)))})
	}
	w.table("Tlv", "(string Input, string Parse, string Validate, string Verify)", rows)
}

